# -*- coding: utf-8 -*-
"""한국 주식 거래비용 — **연도별 실제 요율**과 현재 실거래 비용의 단일 출처.

━━━ 왜 파일을 따로 두나 ━━━
`0.18%` 라는 거래세 가정이 저장소 여섯 곳에 흩어져 하드코딩돼 있었고, 그 값은
**2024년 요율**이다. 2026-01부터 0.20%로 인상됐는데(금투세 폐지에 따른 세수보전)
그걸 모르고 "왕복 0.25~0.4%" 라고 쓰고 있었다. 실전 여부를 가르는 숫자가
낡은 채로 여러 곳에 복사돼 있으면 반드시 틀린 판단을 낳는다.

━━━ ⚠️ 과거 백테스트에 소급 적용하지 말 것 ━━━
2023년 구간을 2026년 세율로 다시 계산하면 **그 시기에 내지 않은 세금을 물리는 것**이라
오히려 틀린다. 기존 백테스트 파일들의 상수는 **일부러 손대지 않았다.**
이 모듈은 **"지금 실제로 굴리면 얼마 드나"** 에만 쓴다.

━━━ 거래세 추이 (매도 시에만 부과) ━━━
    연도    코스피                        코스닥      비고
    2022    0.23% (거래세0.08+농특0.15)   0.23%
    2023    0.20% (0.05+0.15)             0.20%
    2024    0.18% (0.03+0.15)             0.18%       ← 저장소가 쓰던 값
    2025    0.15% (0.00+0.15)             0.15%       금투세 도입 전제로 인하
    2026    0.20% (0.05+0.15)             0.20%       ★인상. 금투세 폐지 세수보전
농어촌특별세(0.15%)는 역사적으로 코스피에만 붙었고 코스닥은 거래세만 올려 맞췄다.
2026년은 결과적으로 두 시장 모두 0.20%로 같다.

━━━ 토스증권 수수료 (2026, 실측 확인 필요) ━━━
    국내주식 매매수수료  KRX 체결 0.015% / NXT 체결 0.014%  (매수·매도 각각)
    **Open API 주문도 동일 — 별도 추가 수수료 없음.**
    ⚠️ 위는 공개 자료 기준이다. API 에 `매매 수수료 조회(KR·US 시장별)` 엔드포인트가
       있으므로, 키를 받으면 **가정하지 말고 그것으로 실측**할 것.

사용: python3 kr_costs.py
"""

TAX_BY_YEAR = {2022: 0.23, 2023: 0.20, 2024: 0.18, 2025: 0.15, 2026: 0.20}

FEE_KRX = 0.015        # 편도, %
FEE_NXT = 0.014        # 편도, % (대체거래소 체결 시)
YEAR = 2026


def round_trip(year=YEAR, nxt=False, slippage=0.0):
    """왕복 비용(%). 매수수수료 + 매도수수료 + 매도거래세 (+ 슬리피지).

    슬리피지는 기본 0 이다 — **모르는 값을 그럴듯한 수로 채우면 안 된다.**
    실주문으로 실측한 뒤 넣을 것(시가 진입 가정과 실제 체결가의 차이)."""
    fee = FEE_NXT if nxt else FEE_KRX
    return fee * 2 + TAX_BY_YEAR[year] + slippage


def main():
    print("  한국 주식 왕복 거래비용 (슬리피지 제외)")
    print(f"  {'연도':<8}{'거래세':>8}{'왕복':>9}")
    for y in sorted(TAX_BY_YEAR):
        mark = "  ← 현재" if y == YEAR else ""
        print(f"  {y:<8}{TAX_BY_YEAR[y]:>7.2f}%{round_trip(y):>8.3f}%{mark}")

    rt = round_trip()
    edge = 0.176        # v13 실측: 규칙 기반 단타 최고 엣지(%/거래)
    print(f"\n  ── 단타 성립 여부 ──")
    print(f"  v13 실측 최고 엣지   {edge:+.3f}% / 거래")
    print(f"  왕복 비용(2026)      {rt:.3f}% / 거래   (슬리피지 0 가정)")
    print(f"  차이                 {edge - rt:+.3f}% / 거래")
    if edge < rt:
        print(f"  → **슬리피지를 0으로 놓아도 적자다.** 매일 회전하면 52거래일에 "
              f"비용만 {rt*52:.1f}%.")
    print(f"\n  ※ 코인(업비트)은 거래세 0%, 수수료 0.05%×2 = 왕복 0.1% 수준이다.")
    print(f"     같은 전략이 크립토에서 되고 한국 주식에서 안 되는 이유의 상당 부분이")
    print(f"     이 비용 차이({rt:.2f}% vs 0.10%)다.")


if __name__ == "__main__":
    main()
